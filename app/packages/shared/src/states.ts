/** Заблокировано тарифом — из макета. */
export interface LockedState { title: string; body: string; action: string }

export function lockedByPlan(feature: string, plan: string, priceDiff?: string): LockedState {
  return {
    title: `${feature} доступен на тарифе ${plan}`,
    body: priceDiff
      ? `Переход добавит ${priceDiff} в месяц. Всё, что настроено, останется на месте.`
      : 'Всё, что настроено, останется на месте.',
    action: 'Сравнить тарифы',
  };
}

export function lockedByPayment(daysLeft: number): LockedState {
  return {
    title: 'Отчёты откроются после оплаты',
    body: `Касса работает ещё ${daysLeft} ${daysLeft === 1 ? 'день' : daysLeft < 5 ? 'дня' : 'дней'} — точка не встанет посреди дня.`,
    action: 'Оплатить',
  };
}

