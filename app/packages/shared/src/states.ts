/** Правило цвета — из макета: красный только про деньги. */
export function toneFor(kind: 'offline' | 'unpaid' | 'shortage' | 'fiscal' | 'ok'): StateTone {
  if (kind === 'offline' || kind === 'unpaid') return 'warn';
  if (kind === 'shortage' || kind === 'fiscal') return 'danger';
  return 'good';
}

